def update_homepage_aktuality():
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "index.html")
    with open(path, encoding="utf-8") as f:
        content = f.read()
    start_marker = "<!-- AKTUALITY:START -->"
    end_marker = "<!-- AKTUALITY:END -->"
    start = content.index(start_marker) + len(start_marker)
    end = content.index(end_marker)
    new_content = content[:start] + "\n" + aktuality_boxes_html(depth=0) + "\n" + content[end:]
    with open(path, "w", encoding="utf-8") as f:
        f.write(new_content)
    print("written index.html (aktuality boxy)")


